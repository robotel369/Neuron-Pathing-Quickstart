package org.firstinspires.ftc.teamcode.opmodes;

import com.qualcomm.robotcore.eventloop.opmode.LinearOpMode;
import com.qualcomm.robotcore.util.ElapsedTime;

import org.firstinspires.ftc.teamcode.neuronpathing.NeuronDrive;
import org.firstinspires.ftc.teamcode.neuronpathing.NeuronLocalizer;
import org.firstinspires.ftc.teamcode.neuronpathing.Pose2D;
import org.firstinspires.ftc.teamcode.subsystems.Flywheel;
import org.firstinspires.ftc.teamcode.subsystems.Gate;
import org.firstinspires.ftc.teamcode.subsystems.Intake;
import org.firstinspires.ftc.teamcode.subsystems.Shooter;
import org.firstinspires.ftc.teamcode.subsystems.Transfer;

/**
 * Autonomous built from Neuron Path Planner output (tools/neuron-path-planner.html).
 * The path is written for both alliances using the planner's `alliance` multiplier;
 * PlannerAutoRed / PlannerAutoBlue pick the side so the Driver Station list has one
 * entry per alliance and there's nothing to select during init.
 *
 * Each planner "shoot" action calls shoot(), which runs the Shooter macro and waits
 * for it to finish before the path continues.
 */
public abstract class PlannerAuto extends LinearOpMode {
    NeuronLocalizer localizer;
    NeuronDrive drive;
    Gate gate;
    Intake intake;
    Transfer transfer;
    Flywheel flywheel;
    Shooter shooter;

    /** Max drive power for every path move. Lowered to 0.6 for testing; the planner output used 1. */
    public static double MAX_SPEED = 0.6;

    /** Once within 5 in / 5 deg of a stop point, how long to keep fine-correcting toward
     *  2 in / 2 deg before moving on anyway. */
    public static double SETTLE_TIMEOUT_MS = 300;
    /** Rough robot speed at full power, used to project how long each move should take. */
    public static double EXPECTED_SPEED_IN_PER_S = 40;
    /** Extra time on top of the projected travel time before a move is skipped. */
    public static double MOVE_TIMEOUT_EXTRA_MS = 750;

    /** -1 for Blue, +1 for Red (the planner's convention). */
    double alliance;

    /** -1 Blue / +1 Red, set by the alliance-specific subclass. */
    protected abstract double alliance();

    @Override
    public void runOpMode() throws InterruptedException {
        alliance = alliance();

        localizer = new NeuronLocalizer(hardwareMap, telemetry, /*xOffsetMm=*/144.0, /*yOffsetMm=*/-144.0);
        drive = new NeuronDrive(hardwareMap, localizer, /*trackWidthIn=*/405.0 / 25.4);
        gate = new Gate(hardwareMap);
        intake = new Intake(hardwareMap);
        transfer = new Transfer(hardwareMap);
        flywheel = new Flywheel(hardwareMap);
        shooter = new Shooter(flywheel, transfer, gate);

        gate.close();
        intake.stop();
        transfer.stop();
        flywheel.stop();

        // calibrate(true) resets the Pinpoint's position to 0, so it runs here in init
        // and the planner's starting pose is set afterwards, at the start of runPath()
        localizer.calibrate(true);

        telemetry.addData("alliance", alliance > 0 ? "RED" : "BLUE");
        telemetry.addLine("Ready. Place the robot on its starting pose and press START.");
        telemetry.update();

        waitForStart();
        if (isStopRequested()) return;

        runPath();

        intake.stop();
        transfer.stop();
        flywheel.stop();
    }

    // ===== Generated by Neuron Path Planner =====
    private void runPath() {
        localizer.setPosition(new Pose2D(-62, -12.5*alliance, Math.toRadians(180 - 0*alliance)));
        shoot();
        drive.goToPoint(new Pose2D(-34, -34.5*alliance, Math.toRadians(180 - -90*alliance)), false, MAX_SPEED);
        driveToTarget();
        drive.splineToPoint(new Pose2D(-37.5, -33.5*alliance, Math.toRadians(180 - -90*alliance)), false, true, 1, MAX_SPEED);
        driveToTarget();
        intake.intake();
        drive.goToPoint(new Pose2D(-37.5, -48*alliance, Math.toRadians(180 - 270*alliance)), false, MAX_SPEED);
        driveToTarget();
        drive.splineToPoint(new Pose2D(-42.5, -34*alliance, Math.toRadians(180 - 270*alliance)), true, true, 0.4, MAX_SPEED);
        driveToTarget();
        drive.goToPoint(new Pose2D(-42.5, -48*alliance, Math.toRadians(180 - 270*alliance)), false, MAX_SPEED);
        driveToTarget();
        drive.goToPoint(new Pose2D(-59.5, -13*alliance, Math.toRadians(180 - 0*alliance)), false, MAX_SPEED);
        driveToTarget();
        shoot();
        drive.splineToPoint(new Pose2D(-59, -35.5*alliance, Math.toRadians(180 - 315*alliance)), true, false, 0.6, MAX_SPEED);
        driveToTarget();
        drive.goToPoint(new Pose2D(-59, -58.5*alliance, Math.toRadians(180 - 315*alliance)), false, MAX_SPEED);
        driveToTarget();
        drive.goToPoint(new Pose2D(-34, -36*alliance, Math.toRadians(180 - 180*alliance)), true, MAX_SPEED);
        driveToTarget();
        drive.goToPoint(new Pose2D(35, -36*alliance, Math.toRadians(180 - 180*alliance)), true, MAX_SPEED);
        driveToTarget();
        drive.goToPoint(new Pose2D(56.5, -12.5*alliance, Math.toRadians(180 - 180*alliance)), false, MAX_SPEED);
        driveToTarget();
        shoot();
    }

    // Runs the shoot macro at the current pose and blocks until it finishes, still
    // holding position and updating every subsystem while it runs.
    private void shoot() {
        shooter.start();
        while (opModeIsActive() && shooter.isBusy()) {
            updateAll();
            telemetry.addData("shooter", shooter.state);
            telemetry.addData("flywheel target", flywheel.getTargetTicksPerSec());
            telemetry.addData("flywheel speed", flywheel.getTicksPerSec());
            telemetry.update();
        }
    }

    // Blocks until the active goToPoint()/splineToPoint() move finishes. NeuronDrive
    // only moves while update() is being called, so every move needs one of these.
    // Moves on early if the final fine-correction takes longer than SETTLE_TIMEOUT_MS,
    // or the whole move takes longer than its projected time (distance / expected speed
    // + MOVE_TIMEOUT_EXTRA_MS), so a target that's hard to hit exactly can't stall auto.
    private void driveToTarget() {
        Pose2D target = drive.getFinalTarget();
        double distance = (target == null) ? 0 : Math.hypot(target.x - drive.pose.x, target.y - drive.pose.y);
        double expectedSpeed = Math.max(1, EXPECTED_SPEED_IN_PER_S * MAX_SPEED);
        double moveTimeoutMs = distance / expectedSpeed * 1000 + MOVE_TIMEOUT_EXTRA_MS;

        ElapsedTime moveTimer = new ElapsedTime();
        ElapsedTime settleTimer = new ElapsedTime();
        boolean settling = false;

        while (opModeIsActive() && drive.isBusy()) {
            updateAll();

            if (drive.driveState == NeuronDrive.DriveState.CLOSEPID) {
                if (!settling) {
                    settling = true;
                    settleTimer.reset();
                }
                if (settleTimer.milliseconds() > SETTLE_TIMEOUT_MS) {
                    telemetry.log().add("Move: settle timed out, continuing");
                    break;
                }
            }
            if (moveTimer.milliseconds() > moveTimeoutMs) {
                telemetry.log().add("Move: timed out after %.0f ms, continuing", moveTimeoutMs);
                break;
            }

            telemetry.addData("state", drive.driveState);
            telemetry.addData("x", drive.pose.x);
            telemetry.addData("y", drive.pose.y);
            telemetry.addData("heading (deg)", Math.toDegrees(drive.pose.h));
            telemetry.addData("intake", intake.state);
            telemetry.addData("flywheel", flywheel.state);
            telemetry.update();
        }
    }

    // Pauses for ms milliseconds while still actively holding position and
    // updating subsystems.
    private void waitMs(double ms) {
        double start = System.currentTimeMillis();
        while (opModeIsActive() && System.currentTimeMillis() - start < ms) {
            updateAll();
            idle();
        }
    }

    private void updateAll() {
        shooter.update();
        drive.update();
        gate.update();
        intake.update();
        transfer.update();
        flywheel.update();
    }
}
